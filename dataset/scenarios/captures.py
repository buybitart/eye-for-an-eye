def _flows(seed, *, clients, port_plan, shape, body, count, gap, jitter=.4, version=4,
           retransmit=False, reorder=False, segments=1, network='203.0.113'):
    stream = rng(seed)
    address_pool = sources(stream, clients, network)
    destination_pool = targets(stream, min(3, clients + 1))
    flows, moment = [], 0.0
    for index in range(count):
        client = address_pool[index % len(address_pool)]
        signature = stack(rng(f'{seed}:{client}'))
        port = port_plan(stream, index)
        flows.append(Flow(moment, client, destination_pool[index % len(destination_pool)], port,
                          shape if isinstance(shape, str) else shape(stream, index),
                          REQUESTS[body] if isinstance(body, str) else REQUESTS[body(stream, index)],
                          retransmit=retransmit and stream.random() < .4,
                          reorder=reorder and stream.random() < .3,
                          segments=segments, version=version, **signature))
        moment += max(.01, gap * stream.uniform(1 - jitter, 1 + jitter))
    return flows


