def behaviour_summary(flows):
    """Environment attributes kept beside a capture for leakage analysis. Never features."""
    times = sorted(flow.time for flow in flows)
    gaps = [round(later - earlier, 6) for earlier, later in zip(times, times[1:])]
    mean = sum(gaps) / len(gaps) if gaps else None
    variance = sum((gap - mean) ** 2 for gap in gaps) / len(gaps) if gaps and mean is not None else None
    sending = [flow for flow in flows if flow.shape not in ('syn_only', 'syn_reset', 'handshake')]
    counts = {}
    for flow in flows:
        counts[flow.shape] = counts.get(flow.shape, 0) + 1
    return {'ports': sorted({flow.port for flow in flows}),
            'destinations': sorted({flow.destination for flow in flows}),
            'request_lengths': sorted({len(flow.request) for flow in sending}),
            'shapes': counts, 'contacts': len(flows),
            'duration_seconds': round(max(times) - min(times), 3) if times else 0.0,
            'source_port_range': 'ephemeral',
            'ttls': sorted({flow.ttl for flow in flows}),
            'windows': sorted({flow.window for flow in flows}),
            'interarrival_mean': mean,
            'interarrival_stdev': variance ** .5 if variance is not None else None,
            'interarrival_min': min(gaps) if gaps else None,
            'interarrival_max': max(gaps) if gaps else None}


def build(root, *, overwrite=False):
    """Render the generated captures. Existing fixtures are referenced, never rewritten."""
    from ..generators.capture import write
    from ..manifest import file_digest, now
    target = Path(root)
    entries = []
    for entry in CAPTURES:
        path = target / (entry['capture_id'] + '.pcap')
        if path.exists() and not overwrite:
            raise FileExistsError('captures are immutable; write a new capture version instead')
        flows = entry['builder'](entry['capture_id'])
        rows, budget = write(path, flows, seed=entry['capture_id'], snaplen=entry.get('snaplen', 65535))
        entries.append({**{k: v for k, v in entry.items() if k != 'builder'},
                        'capture': path.name, 'sha256': file_digest(path), 'packets': len(rows),
                        'flows': len(flows), 'bytes': path.stat().st_size, 'budget': budget,
                        'ipv6': any(flow.version == 6 for flow in flows),
                        'snaplen': entry.get('snaplen', 65535), **behaviour_summary(flows)})
    return {'capture_corpus_version': CAPTURE_CORPUS_VERSION, 'created_at': now(),
            'generated': entries, 'transmitted_packets': 0}
